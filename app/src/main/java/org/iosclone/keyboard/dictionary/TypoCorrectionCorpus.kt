    /**
     * Resolves a fast, deterministic correction for word.
     * Preserves capitalization if input was capitalized or uppercase.
     */
    fun findCorrection(input: String): String? {
        val lower = input.lowercase()
        val fix = typoMap[lower] ?: return null

        return when {
            input.length > 1 && input.all { it.isUpperCase() } -> fix.uppercase()
            input[0].isUpperCase() -> fix.replaceFirstChar { it.uppercase() }
            else -> fix
        }
    }
